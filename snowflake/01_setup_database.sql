USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS FRAUD_DETECTION;
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.RAW;
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.STAGING;
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.DWH;
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.ML;

CREATE WAREHOUSE IF NOT EXISTS FRAUD_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;